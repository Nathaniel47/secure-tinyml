"""Write results/data_report.md: counts, class balance, sample grids and quality problems.

python -m securetinyml.data.report
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import numpy as np
from PIL import Image

from securetinyml.config import DATASET_ORDER, SEEDS
from securetinyml.data.common import INTERIM, ROOT, load_splits

RESULTS = ROOT / "results"


def _hashes(x: np.ndarray) -> list[str]:
    return [hashlib.md5(a.tobytes()).hexdigest() for a in x]  # noqa: S324 (dedup, not security)


def quality(d: dict) -> dict:
    """Exact duplicates inside train, and test images that also appear in train."""
    ht, hs = _hashes(d["x_train"]), _hashes(d["x_test"])
    train_set = set(ht)
    return {
        "dup_in_train": len(ht) - len(train_set),
        "test_in_train": sum(h in train_set for h in hs),
        "x_min_max": (int(d["x_train"].min()), int(d["x_train"].max())),
    }


def sample_grid(d: dict, path: Path, per_class: int = 4, max_classes: int = 12) -> None:
    rows = []
    for c in range(min(len(d["classes"]), max_classes)):
        imgs = d["x_train"][d["y_train"] == c][:per_class]
        if len(imgs) == per_class:
            rows.append(np.concatenate(list(imgs), axis=1))
    Image.fromarray(np.concatenate(rows, axis=0)).save(path)


def section(name: str) -> str:
    d = np.load(INTERIM / f"{name}.npz", allow_pickle=False)
    d = {k: d[k] for k in d.files}
    classes = list(d["classes"])
    q = quality(d)
    ytr, yte = d["y_train"], d["y_test"]
    ctr, cte = np.bincount(ytr, minlength=len(classes)), np.bincount(yte, minlength=len(classes))
    RESULTS.mkdir(exist_ok=True)
    grid = RESULTS / f"samples_{name}.png"
    sample_grid(d, grid)
    out = [f"## {name}", ""]
    out.append(f"- Image size: {d['x_train'].shape[1]}x{d['x_train'].shape[2]} RGB uint8.")
    out.append(f"- Train {len(ytr)}, test {len(yte)}, classes {len(classes)}.")
    for s in SEEDS:
        sp = load_splits(name, s)
        out.append(f"- Seed {s} split: train {len(sp['train'])}, val {len(sp['val'])}.")
    out.append(
        f"- Class balance (train): min {ctr.min()}, max {ctr.max()}, "
        f"ratio {ctr.max() / max(ctr.min(), 1):.1f}x. Test: min {cte.min()}, max {cte.max()}."
    )
    out += ["", "| class | name | train | test |", "|---|---|---|---|"]
    out += [f"| {i} | {c} | {ctr[i]} | {cte[i]} |" for i, c in enumerate(classes)]
    out += ["", f"Sample grid (first rows are classes 0..): `results/{grid.name}`", ""]
    out.append("**Quality checks**")
    out.append(f"- Exact duplicate images inside train: {q['dup_in_train']}.")
    out.append(f"- Test images identical to a train image: {q['test_in_train']}.")
    if "groups_train" in d:
        n_groups = len(np.unique(d["groups_train"]))
        out.append(
            f"- Train images come in {n_groups} tracks (about 30 near-identical frames of one "
            "physical sign). Validation is split by track so frames never straddle train/val."
        )
        sz = d["orig_sizes"]
        out.append(
            f"- Original image sizes before resizing: width {sz[:, 0].min()}-{sz[:, 0].max()}, "
            f"median {int(np.median(sz[:, 0]))}. Small signs are upscaled to "
            f"{d['x_train'].shape[1]} px "
            "and are blurry."
        )
    return "\n".join(out)


def main() -> None:
    parts = [
        "# Data report",
        "",
        "Generated by `python -m securetinyml.data.report`. Counts come from the cached arrays "
        "in `data/interim/`.",
        "",
    ]
    done = []
    for n in DATASET_ORDER:
        if (INTERIM / f"{n}.npz").exists():
            parts.append(section(n))
            done.append(n)
        else:
            parts += [f"## {n}", "", "Not downloaded yet; no numbers.", ""]
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "data_report.md").write_text("\n".join(parts) + "\n", encoding="utf-8")
    print("wrote results/data_report.md for", ", ".join(done))


if __name__ == "__main__":
    main()
